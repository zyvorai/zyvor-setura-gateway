package contract

import (
	"sort"
	"strings"
)

// ExportOptions tune ExportOpenAPI.
type ExportOptions struct {
	Title       string
	Version     string
	Server      string // optional servers[0].url
	MinRequests int64
}

type obj = map[string]any

var skipHeaderParams = map[string]bool{"accept": true, "content-type": true, "authorization": true}

// pathParamNames gives each {id} of a template a distinct name taken from
// the preceding word: /users/{id}/orders/{id} becomes /users/{userId}/orders/{orderId}.
func pathParamNames(tpl string) (string, []string) {
	segs := SplitPath(tpl)
	used := map[string]int{}
	var names []string
	for i, s := range segs {
		if s != VarSegment {
			continue
		}
		name := "id"
		if i > 0 && segs[i-1] != VarSegment && isASCIIWord(segs[i-1]) {
			w := strings.NewReplacer("-", " ", "_", " ", ".", " ").Replace(segs[i-1])
			if f := strings.Fields(w); len(f) > 0 {
				last := f[len(f)-1]
				switch {
				case strings.HasSuffix(last, "ies") && len(last) > 3:
					last = last[:len(last)-3] + "y"
				case strings.HasSuffix(last, "s") && !strings.HasSuffix(last, "ss") && len(last) > 1:
					last = last[:len(last)-1]
				}
				f[len(f)-1] = last
				name = strings.ToLower(f[0][:1]) + f[0][1:]
				for _, p := range f[1:] {
					name += strings.ToUpper(p[:1]) + p[1:]
				}
				name += "Id"
			}
		}
		used[name]++
		if used[name] > 1 {
			name += itoa(used[name])
		}
		names = append(names, name)
		segs[i] = "{" + name + "}"
	}
	return "/" + strings.Join(segs, "/"), names
}

func itoa(n int) string {
	if n < 10 {
		return string(rune('0' + n))
	}
	return itoa(n/10) + string(rune('0'+n%10))
}

func statsObj(d Dist) obj {
	return obj{"p50": d.P50, "p90": d.P90, "p99": d.P99, "max": d.Max, "samples": d.N}
}

// ExportOpenAPI builds an OpenAPI 3.1 document from an inventory. Parameters
// carry names only (every schema is a plain string) and responses carry the
// observed status codes and media types; nothing is invented about bodies.
func ExportOpenAPI(doc *Doc, o ExportOptions) obj {
	if o.Title == "" {
		o.Title = "Observed API"
	}
	if o.Version == "" {
		o.Version = "0.0.0-observed"
	}
	paths := obj{}
	skipped := 0
	exported := 0
	for _, e := range doc.Endpoints {
		if e.Count < o.MinRequests {
			continue
		}
		method := strings.ToLower(e.Method)
		ok := false
		for _, m := range httpMethods {
			if m == e.Method {
				ok = true
			}
		}
		if !ok {
			skipped++
			continue
		}
		path, pnames := pathParamNames(e.Path)
		item, _ := paths[path].(obj)
		if item == nil {
			item = obj{}
			paths[path] = item
		}
		var params []any
		for _, n := range pnames {
			params = append(params, obj{"name": n, "in": "path", "required": true, "schema": obj{"type": "string"}})
		}
		for _, n := range e.Query {
			params = append(params, obj{"name": n, "in": "query", "required": false, "schema": obj{"type": "string"}})
		}
		for _, n := range e.Headers {
			if !skipHeaderParams[n] {
				params = append(params, obj{"name": n, "in": "header", "required": false, "schema": obj{"type": "string"}})
			}
		}
		resp := obj{}
		media := obj{}
		for t := range e.ResponseTypes {
			if t != otherKey {
				media[t] = obj{}
			}
		}
		for _, code := range sortedKeys(e.Status) {
			if code == otherKey {
				continue
			}
			r := obj{"description": "Observed " + code + " (" + plural(e.Status[code], "request") + ")"}
			if len(media) > 0 {
				r["content"] = media
			}
			resp[code] = r
		}
		if len(resp) == 0 {
			resp["default"] = obj{"description": "No response was observed"}
		}
		op := obj{"responses": resp}
		if len(params) > 0 {
			op["parameters"] = params
		}
		if len(e.RequestTypes) > 0 {
			c := obj{}
			for t := range e.RequestTypes {
				if t != otherKey {
					c[t] = obj{}
				}
			}
			if len(c) > 0 {
				op["requestBody"] = obj{"content": c}
			}
		}
		x := obj{"requests": e.Count, "first_seen": e.FirstSeen, "last_seen": e.LastSeen,
			"latency_ms": statsObj(e.Latency), "request_bytes": statsObj(e.RequestBytes), "response_bytes": statsObj(e.ResponseBytes),
			"auth": obj{"protected": e.Auth.Protected, "open": e.Auth.Open}, "status": e.Status}
		if len(e.Routes) > 0 {
			x["routes"] = e.Routes
		}
		if len(e.Backends) > 0 {
			x["backends"] = e.Backends
		}
		if len(e.Headers) > 0 {
			x["headers"] = e.Headers
		}
		op["x-setura-observed"] = x
		item[method] = op
		exported++
	}
	out := obj{"openapi": "3.1.0",
		"info": obj{"title": o.Title, "version": o.Version,
			"description": "Generated by setura contract export from observed gateway traffic. Path templates are inferred, parameter schemas are untyped strings and no body schemas are included."},
		"paths": paths,
		"x-setura-observed": obj{"first_seen": doc.First, "last_seen": doc.Last, "requests": doc.Requests, "endpoints": exported,
			"dropped_requests": doc.DroppedRequests, "unexportable_methods": skipped},
	}
	if o.Server != "" {
		out["servers"] = []any{obj{"url": o.Server}}
	}
	return out
}

// PathKeys returns the exported paths in order (for tests and listings).
func PathKeys(doc obj) []string {
	p, _ := doc["paths"].(obj)
	var k []string
	for s := range p {
		k = append(k, s)
	}
	sort.Strings(k)
	return k
}

func isASCIIWord(s string) bool {
	for i := 0; i < len(s); i++ {
		if !isAlpha(s[i]) && !isDigit(s[i]) && s[i] != '-' && s[i] != '_' && s[i] != '.' {
			return false
		}
	}
	return s != ""
}
