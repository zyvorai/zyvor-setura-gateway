#!/bin/bash
# Sign, package, notarize and staple the macOS builds on the Zyvor Mac mini.
# Run by a maintainer from a laptop AFTER `make dist`; CI never runs it.
#
# Usage: scripts/sign-macos.sh VERSION [--dry-run | --print-remote]
#   --dry-run       check inputs and print the plan; touch nothing and contact nobody
#   --print-remote  print the script that would run on the mini and exit
#
# What it does (see docs/release-process.md):
#   1. copies dist/setura_VERSION_darwin_{arm64,amd64}.tar.gz to the mini over ssh
#   2. starts a generated .command in the mini's GUI session
#      (open -a Terminal): pkgbuild --sign fails over plain ssh with
#      errSecInteractionNotAllowed; the first Installer-key use shows a keychain
#      dialog on the mini where the user clicks "Always Allow"
#   3. there: codesign the binary (hardened runtime, timestamp), pkgbuild a
#      signed installer package, notarize it with
#      xcrun notarytool submit F --keychain-profile Macora-Notary --wait,
#      staple it, run spctl
#   4. copies only the finished .pkg files back to dist/macos/ and writes
#      dist/macos/checksums.txt
#
# Secrets: nothing is copied except the archives and the packages. The notary
# API key (.p8) stays in ~/Downloads on the mini and is never read or copied;
# the notary credentials come from the keychain profile.
# The ssh commands deliberately expand the remote directory on this side.
# shellcheck disable=SC2029
set -euo pipefail

APP_ID=${SETURA_APP_IDENTITY:-"Developer ID Application: ZYVORAI LABS PRIVATE LIMITED (NX667LTDQ2)"}
INSTALLER_ID=${SETURA_INSTALLER_IDENTITY:-"Developer ID Installer: ZYVORAI LABS PRIVATE LIMITED (NX667LTDQ2)"}
NOTARY_PROFILE=${SETURA_NOTARY_PROFILE:-Macora-Notary}
MINI=${SETURA_MINI_HOST:-mini}
PKG_ID=dev.zyvor.setura
WAIT_SECONDS=${SETURA_SIGN_TIMEOUT:-3600}

version=${1:?usage: sign-macos.sh VERSION [--dry-run|--print-remote]}
version=${version#v}
mode=${2:-run}
case $mode in run | --dry-run | --print-remote) ;; *) echo "sign-macos: unknown option $mode" >&2; exit 2 ;; esac
root=$(cd "$(dirname "$0")/.." && pwd)
dist=$root/dist
remote_dir="tt/setura-sign/$version" # relative to the mini's home

# remote_script prints the .command that runs on the mini, in its GUI session.
remote_script() {
	cat <<EOF
#!/bin/zsh
# Generated by scripts/sign-macos.sh for Setura $version. Runs in the GUI session.
cd "\$(dirname "\$0")"
exec > sign.log 2>&1
rm -f status .done
trap 'rc=\$?; if [ \$rc -ne 0 ]; then echo "failed (exit \$rc)" > status; fi; touch .done' EXIT
set -eu
echo "signing Setura $version"
rm -rf out && mkdir out
for arch in arm64 amd64; do
  name=setura_${version}_darwin_\$arch
  rm -rf "\$name" root-\$arch && tar -xzf "\$name.tar.gz"
  codesign --force --options runtime --timestamp --sign "$APP_ID" "\$name/setura"
  codesign --verify --strict --verbose=2 "\$name/setura"
  mkdir -p "root-\$arch/usr/local/bin" "root-\$arch/usr/local/share/man/man1"
  cp "\$name/setura" "root-\$arch/usr/local/bin/setura"
  cp "\$name/man/setura.1" "root-\$arch/usr/local/share/man/man1/setura.1"
  pkgbuild --root "root-\$arch" --identifier "$PKG_ID" --version "$version" --install-location / \\
    --sign "$INSTALLER_ID" "out/\$name.pkg"
  xcrun notarytool submit "out/\$name.pkg" --keychain-profile "$NOTARY_PROFILE" --wait
  xcrun stapler staple "out/\$name.pkg"
  spctl -a -t install -vv "out/\$name.pkg"
done
echo ok > status
EOF
}

if [ "$mode" = --print-remote ]; then remote_script; exit 0; fi

for arch in arm64 amd64; do
	[ -f "$dist/setura_${version}_darwin_$arch.tar.gz" ] || { echo "sign-macos: $dist/setura_${version}_darwin_$arch.tar.gz not found (run make dist VERSION=$version)" >&2; exit 1; }
done

cat <<EOF
Sign Setura $version on ssh $MINI
  application identity: $APP_ID
  installer identity:   $INSTALLER_ID
  notary profile:       $NOTARY_PROFILE (keychain profile; the API key is never copied)
  remote directory:     ~/$remote_dir
  outputs:              $dist/macos/setura_${version}_darwin_{arm64,amd64}.pkg and checksums.txt
EOF
if [ "$mode" = --dry-run ]; then echo "dry run: nothing changed"; exit 0; fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
remote_script > "$tmp/sign.command"
chmod 755 "$tmp/sign.command"

echo "== upload"
ssh "$MINI" "mkdir -p ~/$remote_dir"
scp -q "$dist/setura_${version}_darwin_arm64.tar.gz" "$dist/setura_${version}_darwin_amd64.tar.gz" "$tmp/sign.command" "$MINI:$remote_dir/"

echo "== start in the GUI session (click Always Allow on the mini if asked)"
ssh "$MINI" "rm -f ~/$remote_dir/.done ~/$remote_dir/status && open -a Terminal ~/$remote_dir/sign.command"

echo "== waiting for the mini (up to ${WAIT_SECONDS}s)"
waited=0
until ssh "$MINI" "test -f ~/$remote_dir/.done"; do
	[ "$waited" -lt "$WAIT_SECONDS" ] || { echo "sign-macos: timed out; see ~/$remote_dir/sign.log on the mini" >&2; exit 1; }
	sleep 10
	waited=$((waited + 10))
done
ssh "$MINI" "tail -n 25 ~/$remote_dir/sign.log" || true
status=$(ssh "$MINI" "cat ~/$remote_dir/status" 2>/dev/null || echo "no status")
[ "$status" = ok ] || { echo "sign-macos: failed on the mini: $status" >&2; exit 1; }

echo "== download"
mkdir -p "$dist/macos"
scp -q "$MINI:$remote_dir/out/setura_${version}_darwin_arm64.pkg" "$MINI:$remote_dir/out/setura_${version}_darwin_amd64.pkg" "$dist/macos/"
(
	cd "$dist/macos"
	if command -v sha256sum >/dev/null 2>&1; then sha256sum -- *.pkg > checksums.txt; else shasum -a 256 -- *.pkg > checksums.txt; fi
)
echo "done: $dist/macos"
echo "attach them to the release by hand: gh release upload v$version dist/macos/*.pkg dist/macos/checksums.txt"
